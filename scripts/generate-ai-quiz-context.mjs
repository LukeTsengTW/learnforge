import { createServer } from 'vite'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, relative } from 'node:path'
import process from 'node:process'
import console from 'node:console'

const root = resolve(import.meta.dirname, '..')
const quizRoot = resolve(root, 'src/content/quizzes')
const output = resolve(root, 'supabase/functions/_shared/quiz-context.generated.ts')
const checkOnly = process.argv.includes('--check')

async function quizFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = resolve(directory, entry.name)
    return entry.isDirectory() ? quizFiles(path) : entry.name.endsWith('.quiz.md') ? [path] : []
  }))
  return nested.flat().sort()
}

const server = await createServer({ configFile: false, root, appType: 'custom', server: { middlewareMode: true, hmr: false } })
try {
  const { parseQuiz } = await server.ssrLoadModule('/src/lib/quiz-parser.ts')
  const { toTutorContext } = await server.ssrLoadModule('/scripts/ai-quiz-context.ts')
  const contexts = []
  const identities = new Set()
  const current = new Set()
  const quizzes = new Set()
  const files = await quizFiles(quizRoot)
  if (!files.length) throw new Error('No quiz Markdown files found')
  for (const file of files) {
    const quiz = parseQuiz(await readFile(file, 'utf8'), true)
    const quizIdentity = `${quiz.id}/${quiz.revision}`
    if (quizzes.has(quizIdentity)) throw new Error(`${relative(root, file)}: duplicate quiz revision ${quizIdentity}`)
    quizzes.add(quizIdentity)
    if (quiz.current) {
      if (current.has(quiz.id)) throw new Error(`${relative(root, file)}: duplicate current quiz ${quiz.id}`)
      current.add(quiz.id)
    }
    for (const question of quiz.questions) {
      const identity = `${quizIdentity}/${question.id}`
      if (identities.has(identity)) throw new Error(`${relative(root, file)}: duplicate question ${identity}`)
      identities.add(identity)
      contexts.push(toTutorContext(quiz, question))
    }
  }
  for (const quizIdentity of quizzes) {
    const id = quizIdentity.split('/')[0]
    if (!current.has(id)) throw new Error(`No current revision for quiz ${id}`)
  }
  contexts.sort((a, b) => `${a.quizId}/${a.revision}/${a.questionId}`.localeCompare(`${b.quizId}/${b.revision}/${b.questionId}`))
  const generated = `// Generated by scripts/generate-ai-quiz-context.mjs from canonical Quiz Markdown. Do not edit.\nexport const AI_QUIZ_CONTEXT = ${JSON.stringify(contexts, null, 2)} as const\n`
  if (checkOnly) {
    const actual = await readFile(output, 'utf8').catch(() => '')
    if (actual !== generated) throw new Error('AI Tutor context drift: run npm run generate:ai-context and commit the generated file.')
    console.log(`AI Tutor context matches ${files.length} quizzes and ${contexts.length} questions.`)
  } else {
    await writeFile(output, generated, 'utf8')
    console.log(`Generated ${relative(root, output)} from ${files.length} quizzes and ${contexts.length} questions.`)
  }
} finally {
  await server.close()
}
